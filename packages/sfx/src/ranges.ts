/* The parameter ranges each category draws from. generateSfx stays inside them for every chip (a test checks it),
   and mutateSfx never nudges a field outside them (a hand-edited value that already sits outside is allowed to stay
   where it is). The numbers were set by measuring the generators over thousands of seeds and rounding outward. */
import type { SfxCategory } from "@bleepkit/core";
import {
  FIELD_PATHS,
  type FieldPath,
  type FieldRange,
  TYPE_LIMITS,
} from "./fields.ts";

export interface SfxRanges {
  category: SfxCategory;
  /** Envelope total (attack + sustain + decay) in seconds. `max` is a hard cap: no generated sound is longer. */
  duration: { min: number; max: number };
  /** Every numeric field, narrowed to what the category uses. A field a category never turns on keeps the type limits. */
  fields: Record<FieldPath, FieldRange>;
}

