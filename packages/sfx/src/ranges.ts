export function categoryRanges(category: SfxCategory): SfxRanges {
  const override = OVERRIDES[category];
  const fields = {} as Record<FieldPath, FieldRange>;
  for (const path of FIELD_PATHS) {
    const base = TYPE_LIMITS[path];
    const narrow = override[path];
    fields[path] = narrow
      ? { ...base, max: narrow[1], min: narrow[0] }
      : { ...base };
  }
  return { category, duration: { ...DURATIONS[category] }, fields };
}
