const FALLBACK = "?";

/** Row bitmasks (bit 4 is the leftmost cell) for each supported character. */
const glyphs = new Map<string, number[]>();

function parseRows(spec: string): number[] {
  return spec.split("|").map((row) => {
    let bits = 0;
    for (let i = 0; i < GLYPH_WIDTH; i += 1) {
      bits = bits * 2 + (row[i] === "#" ? 1 : 0);
    }
    return bits;
  });
}

/** The seven row bitmasks for a character (lower case maps to capitals, unknown characters to "?"). */
export function glyphFor(ch: string): number[] {
  if (glyphs.size === 0) {
    for (const [key, spec] of Object.entries(ROWS)) {
      glyphs.set(key, parseRows(spec));
    }
  }
  const upper = ch.toUpperCase();
  return glyphs.get(upper) ?? glyphs.get(FALLBACK) ?? [];
}
