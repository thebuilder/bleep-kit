const cache = new Map<string, string>();

/** Path data for an icon: one run of pixels per row, merged horizontally. */
function pathOf(name: string): string {
  const art = ART[name] ?? ART.info ?? "";
  let d = "";
  for (const [y, row] of art.split("|").entries()) {
    let x = 0;
    while (x < 8) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") {
          w += 1;
        }
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      } else {
        x += 1;
      }
    }
  }
  return d;
}

/** Inline SVG markup for an icon, sized in CSS pixels (a multiple of 8 stays crisp). */
export function icon(name: string, size = 16, cls = ""): string {
  const key = `${name}:${size}:${cls}`;
  let svg = cache.get(key);
  if (!svg) {
    svg = `<svg class="ico ${cls}" width="${size}" height="${size}" viewBox="0 0 8 8" shape-rendering="crispEdges" aria-hidden="true" fill="currentColor"><path d="${pathOf(name)}"/></svg>`;
    cache.set(key, svg);
  }
  return svg;
}

export const hasIcon = (name: string): boolean => name in ART;

/** The icon for a sfx category or channel kind. */
export const categoryIcon = (c: string): string => (hasIcon(c) ? c : "custom");
